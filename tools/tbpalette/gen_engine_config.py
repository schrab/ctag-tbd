#!/usr/bin/env python3
"""Generate the TBPalette engine config for the vendored Rubato plaits tree.

Reads the Rubato Plaits Lab catalog (vendored copy of
alt_firmwares/plaits_lab_catalog/catalog.json) and writes
components/mutable/rubato/rplaits/dsp/engine_config.h.

Registry order = catalog order (minus excluded engines) and IS the TBPalette
`smodel` panel index — never reorder after release, only append.

No engines are excluded: all 98 catalog models link and run on ESP32.
(lpc-speech's word banks are baked in lpc_speech_synth_words.cc; natural-speech
reads its baked natural_speech_data.h bank; formant-speech never dereferences
a word bank.)

Re-run after updating the vendored catalog:
    python3 -I tools/tbpalette/gen_engine_config.py
"""
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CATALOG = os.path.join(
    REPO, 'components/mutable/rubato/alt_firmwares/plaits_lab_catalog/catalog.json')
OUT = os.path.join(REPO, 'components/mutable/rubato/rplaits/dsp/engine_config.h')

# None: the LPC word banks turned out to be baked in
# plaits/dsp/speech/lpc_speech_synth_words.cc (compiled by the dsp glob), so
# lpc-speech links and runs on ESP32 like the other engines.
EXCLUDED_CLASSES = set()
EXCLUDED_IDS = set()


def fnum(v):
    """Format a float the way generate_engine_config.py does: full precision."""
    if isinstance(v, int):
        return '%d.0f' % v
    s = repr(float(v))
    if 'e' in s or 'E' in s:
        raise ValueError('unexpected exponent in catalog gain: %r' % v)
    if '.' not in s:
        s += '.0'
    return s + 'f'


def main():
    d = json.load(open(CATALOG))
    engines = []
    for e in d['engines']:
        if e['id'] in EXCLUDED_IDS or e['source']['className'] in EXCLUDED_CLASSES:
            continue
        engines.append(e)
    n = len(engines)

    # Unique member per engine class (six-op is placed 3x with one member).
    members = []
    seen_members = set()
    for e in engines:
        m = e['source']['member']
        if m not in seen_members:
            seen_members.add(m)
            members.append(m)

    # Unique includes, first-seen order.
    includes = []
    seen_headers = set()
    for e in engines:
        h = e['source']['header'].replace('plaits/', 'rplaits/', 1)
        if h not in seen_headers:
            seen_headers.add(h)
            includes.append(h)

    # Class name -> registry index (first placement) for the behavior masks.
    def index_of(cls):
        for i, e in enumerate(engines):
            if e['source']['className'] == cls:
                return i
        return None

    idx_speech = index_of('SpeechEngine')
    idx_chiptune = index_of('ChiptuneEngine')
    idx_natural = index_of('NaturalSpeechEngine')
    idx_lpc = index_of('LPCSpeechEngine')
    assert idx_speech is not None and idx_chiptune is not None \
        and idx_natural is not None and idx_lpc is not None

    # six-op placements read the three built-in DX7 syx banks through
    # fm_patches_table (the TEST-build fallback; user_data.ptr() is NULL here).
    six_op_idx = [i for i, e in enumerate(engines)
                  if e['source']['className'] == 'SixOpEngine']
    assert len(six_op_idx) == 3

    L = []
    a = L.append
    a('// Generated by tools/tbpalette/gen_engine_config.py — DO NOT EDIT BY HAND.')
    a('//')
    a('// TBPalette build config for the vendored Rubato plaits tree')
    a('// (components/mutable/rubato/rplaits, namespace rplaits). Model count: %d' % n)
    a('// (the full catalog).')
    a('//')
    a('// Registry order = catalog order = TBPalette smodel panel index.')
    a('// NEVER REORDER — only append (panel presets store smodel indices).')
    a('#ifndef PLAITS_DSP_ENGINE_CONFIG_H_')
    a('#define PLAITS_DSP_ENGINE_CONFIG_H_')
    a('')
    a('#define PLAITS_HAS_TERRAIN_BANK 0')
    a('#define PLAITS_WAVE_TERRAIN_FACTORY_MASK 0xff')
    a('#define PLAITS_HAS_WAVETABLE_BANK 0')
    a('#define PLAITS_WAVETABLE_FACTORY_MASK 0x07')
    a('#define PLAITS_HAS_CUSTOM_WAVE_LINES 0')
    a('#ifndef PLAITS_BUILD_ENABLE_SYNC_INPUT')
    a('#define PLAITS_BUILD_ENABLE_SYNC_INPUT 0')
    a('#endif')
    a('')
    a('// The count must be defined before build_config.h sees it (voice.h order).')
    a('#define PLAITS_ENGINE_COUNT %d' % n)
    a('')
    for h in includes:
        a('#include "%s"' % h)
    a('')
    a('#define PLAITS_HAS_SPEECH_ENGINE 1')
    a('#define PLAITS_HAS_LPC_WORDS_ENGINE 1')
    a('#define PLAITS_HAS_NATURAL_SPEECH_ENGINE 1')
    a('#define PLAITS_HAS_CHIPTUNE_ENGINE 1')
    a('#define PLAITS_HAS_USER_DATA_BANK 1')
    a('#define PLAITS_HAS_USER_DATA_BANK_OVERRIDE 0')
    a('#define PLAITS_HAS_CUSTOM_MODEL_DATA 0')
    a('')
    a('// voice.cc addresses the natural-speech member through this macro; the')
    a('// generated hosted configs define it alongside the mask.')
    a('#if PLAITS_HAS_NATURAL_SPEECH_ENGINE')
    a('#define PLAITS_NATURAL_SPEECH_ENGINE_MEMBER %s' %
      next(e['source']['member'] for e in engines
           if e['source']['className'] == 'NaturalSpeechEngine'))
    a('#endif')
    a('')
    a('#define PLAITS_ENGINE_MEMBERS \\')
    for m in members:
        cls = next(e['source']['className'] for e in engines
                   if e['source']['member'] == m)
        a('  %s %s; \\' % (cls, m))
    L[-1] = L[-1][:-2]  # strip the trailing ' \' of the last member
    a('')
    a('// Gains are the catalog\'s measured postProcessing values.')
    a('#define PLAITS_REGISTER_ENGINES(registry) do { \\')
    for e in engines:
        pp = e['postProcessing']
        a('  (registry).RegisterInstance(&%s, %s, %s, %s); \\' % (
            e['source']['member'],
            'true' if pp['alreadyEnveloped'] else 'false',
            fnum(pp['outGain']), fnum(pp['auxGain'])))
    a('} while (0)')
    a('')
    a('namespace rplaits {')
    a('')
    a('#if PLAITS_HAS_USER_DATA_BANK')
    a('// -1 = no user-data bank. The three six-op placements read the built-in')
    a('// DX7 syx banks through fm_patches_table (user_data.ptr() is NULL in the')
    a('// ctag build, which defines TEST).')
    bank = [-1] * n
    for b, i in enumerate(six_op_idx):
        bank[i] = b
    rows = []
    for r in range(0, n, 16):
        rows.append(', '.join(str(x) for x in bank[r:r + 16]))
    a('static const int8_t kEngineUserDataBank[%d] = {' % n)
    for r in rows:
        a('  %s,' % r)
    a('};')
    a('#endif  // PLAITS_HAS_USER_DATA_BANK')
    a('')
    a('// Behavior masks are uint64_t (ctag raised the 32-slot ceiling; voice.cc')
    a('// shifts with 1ull). Bit N = registry slot N.')
    a('#if PLAITS_HAS_SPEECH_ENGINE')
    a('static const uint64_t kSpeechEngineMask = (1ull << %d);' % idx_speech)
    a('#endif')
    a('#if PLAITS_HAS_LPC_WORDS_ENGINE')
    a('static const uint64_t kLPCWordsEngineMask = (1ull << %d);' % idx_lpc)
    a('#endif')
    a('#if PLAITS_HAS_NATURAL_SPEECH_ENGINE')
    a('static const uint64_t kNaturalSpeechEngineMask = (1ull << %d);' % idx_natural)
    a('#endif')
    a('#if PLAITS_HAS_CHIPTUNE_ENGINE')
    a('static const uint64_t kChiptuneEngineMask = (1ull << %d);' % idx_chiptune)
    a('#endif')
    a('')
    a('}  // namespace rplaits')
    a('')
    a('#endif  // PLAITS_DSP_ENGINE_CONFIG_H_')
    a('')

    with open(OUT, 'w') as f:
        f.write('\n'.join(L))
    print('wrote %s: %d engines, %d unique members, %d includes' %
          (OUT, n, len(members), len(includes)))
    print('six-op slots:', six_op_idx,
          'speech:', idx_speech, 'chiptune:', idx_chiptune,
          'natural:', idx_natural)


if __name__ == '__main__':
    main()
